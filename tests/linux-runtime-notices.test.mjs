async function fixture(){
  assert.ok(existsSync(script),'Missing Linux runtime notice delivery helper');
  const directory=await mkdtemp(join(tmpdir(),'taggroove-linux-notices-'));
  try{
    const spec=JSON.parse(await readFile(join(root,'scripts/notices/linux-runtime-material.json'),'utf8'));
    const records=[...spec.archives.flatMap(item=>item.notice_members),
      ...Object.values(spec.recipes).flatMap(item=>item.files),...spec.evidence_files];
    for(const record of records){
      const target=join(directory,record.source_file);await mkdir(dirname(target),{recursive:true});
      await copyFile(join(root,record.source_file),target);
    }
    const target=join(directory,'scripts/notices/linux-runtime-material.json');
    await mkdir(dirname(target),{recursive:true});await writeFile(target,JSON.stringify(spec));
    return directory;
  }catch(error){await rm(directory,{recursive:true,force:true});throw error;}
}

function rtfText(rtf){
  assert.doesNotMatch(rtf,/[^\t\r\n\x20-\x7e]/,'RTF transport must remain ASCII');
  const marker='\\fs18 ',start=rtf.indexOf(marker);
  assert.ok(start>=0);assert.ok(rtf.endsWith('}\n'));
  return rtf.slice(start+marker.length,-2).replace(/\\u(-?\d+)\?|\\par\n|\\tab |\\[\\{}]/g,(token,value)=>{
    if(value!==undefined)return String.fromCharCode(Number(value)&65535);
    if(token==='\\par\n')return '\n';
    if(token==='\\tab ')return '\t';
    return token[1];
  });
}

test('Linux notice delivery is source-bound and current without a source archive cache',()=>{
  assert.ok(existsSync(script),'Missing Linux runtime notice delivery helper');
  checked(delivery(root,'--check'));
  const payload=readFileSync(join(root,'THIRD_PARTY_LINUX.md'),'utf8');
  assert.match(payload,/Copyright \(c\) 2018-2021 Microsoft Corporation, Daan Leijen/);
  const common=readFileSync(join(root,'THIRD_PARTY_NOTICES.md'),'utf8');
  assert.equal(common.split(begin).length-1,1);assert.equal(common.split(end).length-1,1);
  assert.ok(common.includes(payload),'the complete source-bound payload reaches common notices');
});

test('generation preserves other sections byte-for-byte and Unicode survives installer RTF',async()=>{
  const directory=await fixture();
  try{
    const original='Manual © Zoë — 音楽 🎵\r\nLiteral {braces} and \\object\tstay text.\n'
      +'<!-- BEGIN GENERATED DEPENDENCY NOTICES -->\nExisting dependency notice\n<!-- END GENERATED DEPENDENCY NOTICES -->\n'
      +'<!-- BEGIN GENERATED ANDROID NOTICES -->\nExisting Android notice\n<!-- END GENERATED ANDROID NOTICES -->\n'
      +'<!-- BEGIN GENERATED NATIVE NOTICES -->\nExisting native notice\n<!-- END GENERATED NATIVE NOTICES -->\n\n\n';
    await writeFile(join(directory,'THIRD_PARTY_NOTICES.md'),original);
    checked(delivery(directory,'--generate'));checked(delivery(directory,'--check'));
    const payload=await readFile(join(directory,'THIRD_PARTY_LINUX.md'),'utf8');
    const common=await readFile(join(directory,'THIRD_PARTY_NOTICES.md'),'utf8');
    assert.ok(common.startsWith(original),'retain all observed manual/other-generated bytes');
    assert.ok(common.includes(payload));
    assert.equal(rtfText(await readFile(join(directory,'THIRD_PARTY_NOTICES.rtf'),'ascii')),
      common.replace(/\r\n/g,'\n').replace(/\r/g,'\n'));
    const before=await Promise.all(outputs.map(name=>readFile(join(directory,name))));
    checked(delivery(directory,'--generate'));
    for(let index=0;index<outputs.length;index++)
      assert.deepEqual(await readFile(join(directory,outputs[index])),before[index],'generation is idempotent');
    const suffix='\r\nManual suffix after Linux notices.\r\n';
    await writeFile(join(directory,'THIRD_PARTY_NOTICES.md'),common+suffix);
    checked(delivery(directory,'--generate'));
    assert.equal(await readFile(join(directory,'THIRD_PARTY_NOTICES.md'),'utf8'),common+suffix);
  }finally{await rm(directory,{recursive:true,force:true});}
});

test('check refuses each stale output without rewriting or omitting another output',async()=>{
  const directory=await fixture();
  try{
    await writeFile(join(directory,'THIRD_PARTY_NOTICES.md'),'Manual notices\n');
    checked(delivery(directory,'--generate'));
    for(const name of outputs){
      const path=join(directory,name),original=await readFile(path);
      await writeFile(path,Buffer.concat([original,Buffer.from('stale')]));
      const checkedResult=delivery(directory,'--check');
      assert.notEqual(checkedResult.status,0,name);assert.match(checkedResult.stderr,/Stale/);
      assert.deepEqual(await readFile(path),Buffer.concat([original,Buffer.from('stale')]));
      await writeFile(path,original);
    }
    const spec=JSON.parse(await readFile(join(directory,'scripts/notices/linux-runtime-material.json'),'utf8'));
    await writeFile(join(directory,spec.archives.find(item=>item.id==='mimalloc2').notice_members[0].source_file),'changed notice');
    const before=await Promise.all(outputs.map(name=>readFile(join(directory,name))));
    assert.notEqual(delivery(directory,'--generate').status,0,'refuse changed retained supplier bytes');
    for(let index=0;index<outputs.length;index++)
      assert.deepEqual(await readFile(join(directory,outputs[index])),before[index]);
  }finally{await rm(directory,{recursive:true,force:true});}
});

