#!/usr/bin/env python3
"""Regenerate the portable LCID table from a pinned, locally supplied .NET file.

Fetch the source URL in actions_lcid.source.json, then pass that local path.
Use --check to verify committed output without changing it. No network access.
"""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import re
import subprocess

COMMIT = "60629d14374c56f1cb51819049ad1fa529307f8d"
SHA256 = "ab04bf41c61149233ad7bc04279637426e5a04c8f18f6d979d639ad1ff0f8bee"
SOURCE = (
    f"https://raw.githubusercontent.com/dotnet/runtime/{COMMIT}/"
    "src/libraries/System.Private.CoreLib/src/System/Globalization/IcuLocaleData.cs"
)


def extract(raw):
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError("Source does not match the pinned SHA-256")
    text = raw.decode("utf-8-sig")

    def array(name):
        body = text.split(f"ReadOnlySpan<byte> {name} =>", 1)[1].split("[", 1)[1].split("];", 1)[0]
        body = re.sub(r"//[^\n]*", "", body)
        return bytes(int(value, 0) for value in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", body))

    names_body = text.split("ReadOnlySpan<byte> CultureNames =>", 1)[1].split(";", 1)[0]
    names = "".join(re.findall(r'"([^"\\]*)"u8', names_body)).encode("ascii")
    indexes = array("LocalesNamesIndexes")
    numeric = array("NameIndexToNumericData")
    lookup = array("LcidToCultureNameIndices")
    assert len(indexes) == 864 * 2 and len(numeric) == 864 * 18
    assert len(lookup) == 448 * 4  # Upstream's 488-row comment is stale.

    def name_at(first, second):
        start = (first << 4) | (second >> 4)
        return names[start:start + (second & 15)].decode("ascii")

    rows = {name_at(indexes[i], indexes[i + 1]): i // 2 for i in range(0, len(indexes), 2)}
    assert len(rows) == 864
    boundaries = [0] + [
        int(re.search(rf"LcidSortPrefix{i}Index = (\d+);", text)[1])
        for i in range(1, 6)
    ] + [len(lookup)]
    result = {}
    for sort, (start, end) in enumerate(zip(boundaries, boundaries[1:])):
        assert start % 4 == 0 and end % 4 == 0
        for i in range(start, end, 4):
            lcid = (sort << 16) | (lookup[i] << 8) | lookup[i + 1]
            row = rows[name_at(lookup[i + 2], lookup[i + 3])] * 18
            ansi = ((numeric[row + 4] & 0xf0) >> 4) | (numeric[row + 3] << 4)
            assert lcid not in result
            result[lcid] = ansi
    assert len(result) == 448 and sum(value != 0 for value in result.values()) == 354
    assert {key: result[key] for key in [1033, 1049, 1041, 1043]} == {
        1033: 1252, 1049: 1251, 1041: 932, 1043: 1252,
    }
    # Never infer a custom/system locale from duplicate numeric culture rows.
    assert all(key not in result for key in [0, 0x400, 0x800, 0x1000])
    return result


def outputs(mapping):
    by_page = defaultdict(list)
    for lcid, page in mapping.items():
        if page:
            by_page[page].append(lcid)
    lines = [
        "// Generated by scripts/generate-lcid-ansi.py; do not edit by hand.",
        "// Derived from .NET runtime v10.0.0 IcuLocaleData.cs (MIT).",
        f"// Source: {SOURCE}",
        f"// SHA-256: {SHA256}",
        "// Uses LCIDToLocaleName lookup, including sort prefixes, then AnsiCodePage.",
        "// License: ../../../src/licenses/dotnet-runtime-MIT.txt",
        "// Frozen portable defaults; Windows user overrides/system sentinels are not queried.",
        "pub(super) fn ansi_codepage(lcid: u32) -> Option<u16> {",
        "    Some(match lcid {",
    ]
    for page, lcids in sorted(by_page.items()):
        lines.append("        " + " | ".join(hex(value) for value in sorted(lcids)) + f" => {page},")
    lines += ["        _ => return None,", "    })", "}", ""]
    rust = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input="\n".join(lines), text=True, capture_output=True, check=True,
    ).stdout
    provenance = {
        "component": ".NET runtime locale data", "version": "v10.0.0",
        "commit": COMMIT, "source": SOURCE, "sha256": SHA256,
        "generator": "scripts/generate-lcid-ansi.py",
        "method": "LCIDToLocaleName sort partitions and packed culture-name indexes; GetLocaleDataNumericPart(AnsiCodePage).",
        "lcids": len(mapping), "nonzero_ansi": sum(value != 0 for value in mapping.values()),
        "zero_ansi_refused": sum(value == 0 for value in mapping.values()),
        "windows_runtime_qualified": False,
    }
    return rust, json.dumps(provenance, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_file", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rust, provenance = outputs(extract(args.source_file.read_bytes()))
    root = Path(__file__).resolve().parents[1] / "crates/tag-core/src"
    for name, content in [("actions_lcid.rs", rust), ("actions_lcid.source.json", provenance)]:
        path = root / name
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f"Stale generated output: {path}")
        else:
            path.write_text(content)
    print("Verified 448 LCIDs: 354 nonzero ANSI mappings; 94 zero-ANSI entries refused.")


if __name__ == "__main__":
    main()
